export type Word = keyof typeof WORDS;

/** The word `key` in `lang`, with `{name}` replaced from `values`. */
export function word(lang: Lang, key: Word, values: Record<string, string | number> = {}): string {
  const text: string = WORDS[key][lang === "zh" ? 0 : 1];
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}

