#!/usr/bin/env python3
"""Validate format family counts and reproduce the public support matrix."""

import argparse
import json
import re
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "crates/aa-core/src/formats.json"
MATRIX = ROOT / "docs/FORMATS.md"


def render(catalogue):
    rows = catalogue["formats"]
    counts = Counter(row["group"] for row in rows if row["state"] == "implemented")
    total = counts["primary"] + counts["compression"]
    lines = [
        "# Supported format profiles",
        "",
        "<!-- Generated by tools/formats/check.py --write; edit crates/aa-core/src/formats.json. -->",
        "",
        f"This catalogue tracks **{counts['primary']} primary input-format families + "
        f"{counts['compression']} compression formats = {total} entries**, and "
        f"**{counts['declaration']} declaration families** tracked separately.",
        "",
        catalogue["counting_policy"],
        "",
        "The declaration list is maintained separately from primary inputs and nested structures.",
        "Each row describes a bounded profile. Evidence links identify implementations and",
        "existing scope records; they do not establish every variant or platform was tested.",
        "See [limitations](LIMITATIONS.md) for qualification boundaries. Planned entries",
        "contribute nothing to the implementation total. HTML/PDF/JSON report outputs,",
        "directory workflows and nested metadata structures are not primary input families.",
        "",
        "The same catalogue is available offline as `analyze-anything formats --json`.",
        "",
    ]
    for state, title in [("implemented", "Implemented profiles"), ("planned", "Planned profiles")]:
        lines.extend([f"## {title}", "", "| Family | Group | Aliases | Scope and evidence | Limits |", "|---|---|---|---|---|"])
        for row in rows:
            if row["state"] != state:
                continue
            aliases = ", ".join(row["aliases"]) or "—"
            evidence = " ".join(f"[record {i + 1}](../{path})" for i, path in enumerate(row["evidence"]))
            cell = row["profile"] + (" " + evidence if evidence else "")
            values = [row["name"], row["group"], aliases, cell, " ".join(row["limitations"])]
            lines.append("| " + " | ".join(value.replace("|", "\\|").replace("\n", " ") for value in values) + " |")
        lines.append("")
    return "\n".join(lines)


def validate(catalogue):
    assert catalogue["schema_version"] == 1, "unsupported catalogue schema"
    ids = set()
    for row in catalogue["formats"]:
        assert row["id"] not in ids, f"duplicate format ID: {row['id']}"
        ids.add(row["id"])
        assert row["group"] in {"primary", "compression", "declaration"}, row["id"]
        assert row["state"] in {"implemented", "planned"}, row["id"]
        assert len(row["aliases"]) == len(set(row["aliases"])), f"duplicate alias in {row['id']}"
        assert row["profile"] and row["limitations"], f"missing scope/limits: {row['id']}"
        if row["state"] == "implemented":
            assert row["evidence"], f"missing evidence: {row['id']}"
        for path in row["evidence"]:
            assert not Path(path).is_absolute() and ".." not in Path(path).parts, f"invalid evidence path: {path}"
            assert (ROOT / path).is_file(), f"missing evidence: {path}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the support matrix")
    args = parser.parse_args()
    catalogue = json.loads(SOURCE.read_text(encoding="utf-8"))
    validate(catalogue)
    expected = render(catalogue)
    if args.write:
        MATRIX.write_text(expected, encoding="utf-8", newline="\n")
    else:
        assert MATRIX.is_file() and MATRIX.read_text(encoding="utf-8") == expected, (
            "support matrix differs; run python tools/formats/check.py --write"
        )
    counts = Counter(row["group"] for row in catalogue["formats"] if row["state"] == "implemented")
    primary, compression, declarations = counts["primary"], counts["compression"], counts["declaration"]
    total = primary + compression
    public = {
        ROOT / "README.md": f"**{primary} primary format families + {compression} compression formats ({total} total)**, with {declarations} declaration families tracked separately. See the [supported profiles and limits](docs/FORMATS.md), or run `analyze-anything formats --json`.",
        ROOT / "README.zh-CN.md": f"**{primary} 类主要格式＋{compression} 种压缩格式（共 {total} 类）**，另列 {declarations} 类声明格式。详见[支持范围与限制](docs/FORMATS.md)，或运行 `analyze-anything formats --json`。",
        ROOT / "site/index.html": f'<a class="chip" href="https://github.com/atomsprout/analyze-anything/blob/main/docs/FORMATS.md">{total} format families</a>',
    }
    pattern = re.compile(r"(<!-- formats:begin -->\n).*?(\n\s*<!-- formats:end -->)", re.DOTALL)
    for path, body in public.items():
        text = path.read_text(encoding="utf-8")
        assert len(pattern.findall(text)) == 1, f"missing/duplicate format markers: {path}"
        expected_public = pattern.sub(lambda match: match[1] + body + match[2], text)
        if args.write:
            path.write_text(expected_public, encoding="utf-8", newline="\n")
        else:
            assert text == expected_public, f"public count differs: {path}; run tools/formats/check.py --write"
    print(f"Format catalogue checked: {counts['primary']} primary + {counts['compression']} compression; "
          f"{counts['declaration']} declaration families")


if __name__ == "__main__":
    main()
